"""2026-10-23: sibling poms without a root pom get a generated aggregator; an EAR pom without its modules is rejected
(sbmig.analyze.aggregator)."""
from __future__ import annotations

import shutil
from pathlib import Path

from sbmig.analyze.aggregator import (PROJECT_NAME_PROPERTY, aggregator_pom_text, ear_without_modules,
                                      plan_aggregator, write_aggregator)
from sbmig.analyze.analyzer import PathView
from sbmig.analyze.pom_parser import parse_poms

REPO = Path(__file__).resolve().parents[2]
FIXTURE = REPO / "fixtures" / "projects" / "ear-sibling-poms"


def _pom(gid: str | None, aid: str, packaging: str = "jar", deps: str = "", modules: str = "",
         version: str = "1.0.0") -> str:
    g = f"<groupId>{gid}</groupId>" if gid else ""
    mods = f"<modules>{modules}</modules>" if modules else ""
    return (f'<project xmlns="http://maven.apache.org/POM/4.0.0"><modelVersion>4.0.0</modelVersion>{g}'
            f"<artifactId>{aid}</artifactId><version>{version}</version><packaging>{packaging}</packaging>{mods}"
            f"<dependencies>{deps}</dependencies></project>")


def _dep(gid: str, aid: str, typ: str = "") -> str:
    t = f"<type>{typ}</type>" if typ else ""
    return f"<dependency><groupId>{gid}</groupId><artifactId>{aid}</artifactId><version>1.0.0</version>{t}</dependency>"


def _tree(tmp_path: Path, files: dict[str, str]) -> PathView:
    for rel, text in files.items():
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return PathView(tmp_path)


def test_fixture_gets_an_aggregator_in_dependency_order(tmp_path):
    shutil.copytree(FIXTURE, tmp_path / "p")
    ws = PathView(tmp_path / "p")
    plan = plan_aggregator(ws)
    assert plan is not None
    assert plan.modules == ["APP/BATCH", "APP/WEB", "APP/EAR"]            # BATCH ← WEB ← EAR
    assert (plan.group_id, plan.version, plan.name) == ("com.example.portal", "1.0.0", "portal")
    assert plan.artifact_id == "portal-aggregator"                        # the EAR already is com.example.portal:portal
    assert plan.excluded == [] and "APP/EAR → APP/BATCH, APP/WEB" in plan.reason
    assert write_aggregator(ws, plan) == "pom.xml"
    poms, warnings = parse_poms(ws)
    root = next(p for p in poms if p.path == "pom.xml")
    assert not warnings and root.packaging == "pom" and root.modules == plan.modules
    assert root.properties[PROJECT_NAME_PROPERTY] == "portal"
    assert plan_aggregator(ws) is None                                    # a root pom exists now
    assert ear_without_modules(ws) is None


def test_no_aggregator_for_a_single_pom_or_an_existing_root(tmp_path):
    assert plan_aggregator(_tree(tmp_path / "a", {"pom.xml": _pom("g", "a")})) is None
    assert plan_aggregator(_tree(tmp_path / "b", {"x/pom.xml": _pom("g", "x")})) is None
    two = {"pom.xml": _pom("g", "root", "pom", modules="<module>x</module>"), "x/pom.xml": _pom("g", "x"),
           "y/pom.xml": _pom("g", "y", deps=_dep("g", "x"))}
    assert plan_aggregator(_tree(tmp_path / "c", two)) is None


def test_unlinked_poms_are_not_aggregated(tmp_path):
    ws = _tree(tmp_path, {"a/pom.xml": _pom("g", "a", "war"), "b/pom.xml": _pom("g", "b", "war")})
    assert plan_aggregator(ws) is None                                    # independent apps: no link
    ws2 = _tree(tmp_path / "two-groups", {
        "a/pom.xml": _pom("g", "a", "war", deps=_dep("g", "a-lib")), "a-lib/pom.xml": _pom("g", "a-lib"),
        "b/pom.xml": _pom("h", "b", "war", deps=_dep("h", "b-lib")), "b-lib/pom.xml": _pom("h", "b-lib")})
    assert plan_aggregator(ws2) is None                                   # two separate applications


def test_war_name_property_groups_and_left_out_poms(tmp_path):
    ws = _tree(tmp_path, {
        "web/pom.xml": _pom("kr.co.x", "shopWeb", "war", deps=_dep("${project.groupId}", "shopCore")),
        "core/pom.xml": _pom("kr.co.x", "shopCore"),
        "tools/pom.xml": _pom("kr.co.x", "tools")})
    plan = plan_aggregator(ws)
    assert plan is not None and plan.modules == ["core", "web"] and plan.excluded == ["tools/pom.xml"]
    assert (plan.name, plan.artifact_id) == ("shopWeb", "shopWeb-aggregator")    # no EAR: the WAR names it
    text = aggregator_pom_text(plan)
    assert "<module>core</module>" in text and "generated by sbmig" in text


def test_nested_aggregator_top_links_through_its_modules(tmp_path):
    ws = _tree(tmp_path, {
        "lib/pom.xml": _pom("g", "lib-parent", "pom", modules="<module>util</module>"),
        "lib/util/pom.xml": _pom("g", "util"),
        "app/pom.xml": _pom("g", "app", "war", deps=_dep("g", "util"))})
    plan = plan_aggregator(ws)
    assert plan is not None and plan.modules == ["lib", "app"] and plan.name == "app"


def test_ear_without_its_modules_is_rejected(tmp_path):
    ear = (FIXTURE / "APP" / "EAR" / "pom.xml").read_text(encoding="utf-8")
    ws = _tree(tmp_path / "ear-only", {"pom.xml": ear})
    why = ear_without_modules(ws)
    assert why and "portalWEB (war)" in why and "portalBATCH (jar)" in why and "every module" in why
    assert plan_aggregator(ws) is None
    present = _tree(tmp_path / "with-modules", {
        "pom.xml": _pom("g", "app", "ear", deps=_dep("g", "web", "war")), "web/pom.xml": _pom("g", "web", "war")})
    assert ear_without_modules(present) is None                           # its module is in the tree
    third_party = _tree(tmp_path / "libs-only", {"pom.xml": _pom("g", "app", "ear",
                                                                 deps=_dep("commons-io", "commons-io"))})
    assert ear_without_modules(third_party) is None                       # only library jars for lib/
    assert ear_without_modules(_tree(tmp_path / "jar", {"pom.xml": _pom("g", "x")})) is None
