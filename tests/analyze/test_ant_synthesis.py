def write(root: Path, rel: str, text: str) -> Path:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    return p


def make_jar(root: Path, rel: str, entries: dict[str, bytes | str]) -> Path:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(p, "w") as zf:
        for name, data in entries.items():
            zf.writestr(name, data)
    return p


def sha1_of(p: Path) -> str:
    return hashlib.sha1(p.read_bytes()).hexdigest()


def ant_webapp(base: Path, name: str = "hello-web") -> Path:
    """The test Ant webapp: properties + javac + copy + war, a servlet, web.xml, a JSP and four stub jars."""
    src = base / name
    write(src, "build.xml", WEB_BUILD_XML)
    write(src, "build.properties", "javac.level=1.6\napp.version=2.3.1\n")
    write(src, "src/com/acme/web/HelloServlet.java", SERVLET)
    write(src, "src/com/acme/web/messages.properties", "hello=Hello\n")
    write(src, "WebContent/WEB-INF/web.xml", '<?xml version="1.0"?>\n<web-app version="2.5"></web-app>\n')
    write(src, "WebContent/index.jsp", '<%@ page contentType="text/html" %>\n<html></html>\n')
    lib = "WebContent/WEB-INF/lib"
    make_jar(src, f"{lib}/commons-lang-2.6.jar", {
        "META-INF/maven/commons-lang/commons-lang/pom.properties":
            "#Generated by Maven\ngroupId=commons-lang\nartifactId=commons-lang\nversion=2.6\n",
        "org/apache/commons/lang/StringUtils.class": CLASS})
    make_jar(src, f"{lib}/servlet-api-2.5.jar", {"javax/servlet/Servlet.class": CLASS})
    make_jar(src, f"{lib}/acme-util-1.0.jar", {"com/acme/util/X.class": CLASS})
    make_jar(src, f"{lib}/old-report.jar", {"com/old/report/R.class": CLASS,
                                            "META-INF/MANIFEST.MF": "Manifest-Version: 1.0\nImplementation-Title: Old "
                                                                    "Report\n"})
    return src


class FakeLookup:
    """A sha1 lookup that never touches the network."""

    def __init__(self, table: dict[str, tuple[str, str, str]] | None = None):
        self.table = table or {}
        self.asked: list[str] = []
        self.note = ""

    def find(self, sha1: str):
        self.asked.append(sha1)
        hit = self.table.get(sha1)
        self.note = "" if hit else "sha1 not found (fake repository)"
        return hit


def _pom(ws) -> ET.Element:
    return ET.fromstring((ws.root / "pom.xml").read_bytes())


def _deps(root: ET.Element) -> dict[str, dict[str, str]]:
    out = {}
    for d in root.findall("m:dependencies/m:dependency", NS):
        vals = {c.tag.split("}")[1]: (c.text or "") for c in d}
        out[f"{vals['groupId']}:{vals['artifactId']}"] = vals
    return out


