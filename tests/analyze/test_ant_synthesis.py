def test_two_unknown_jars_with_the_same_file_name_are_declared_at_their_own_paths(tmp_path, make_ws, cfg):
    """2026-10-29: no copy, no sha1 prefixes — each unknown-but-used jar is declared at its own as-is path from the
    top-level pom directory, and the two declarations get distinct artifactIds (name clash → sha1 suffix)."""
    src = tmp_path / "src" / "dup"
    write(src, "build.xml", "<project name='dup'><target name='c'><javac srcdir='src'/></target></project>")
    write(src, "src/com/x/A.java", "package com.x;\nimport com.acme.util.X;\nimport com.acme.other.Y;\n"
                                   "public class A {}\n")
    write(src, "web/WEB-INF/web.xml", "<web-app/>")
    web_jar = make_jar(src, "web/WEB-INF/lib/acme-util-1.0.jar", {"com/acme/util/X.class": CLASS})
    root_jar = make_jar(src, "lib/acme-util-1.0.jar", {"com/acme/other/Y.class": CLASS})
    ws = make_ws(src)
    res = synthesize_pom(ws, cfg, lookup=FakeLookup())
    assert res.ok and res.unknown_jars == ["web/WEB-INF/lib/acme-util-1.0.jar", "lib/acme-util-1.0.jar"]
    assert (ws.root / "web/WEB-INF/lib/acme-util-1.0.jar").read_bytes() == web_jar.read_bytes()
    assert (ws.root / "lib/acme-util-1.0.jar").read_bytes() == root_jar.read_bytes()
    assert not any(p.name.endswith("-acme-util-1.0.jar") for p in (ws.root / "lib").iterdir())   # no prefixed copy
    assert not any(w.startswith("copied ") for w in res.warnings)
    paths = {d["artifactId"]: d["systemPath"] for d in _deps(_pom(ws)).values()}
    assert set(paths.values()) == {"${maven.multiModuleProjectDirectory}/web/WEB-INF/lib/acme-util-1.0.jar",
                                   "${maven.multiModuleProjectDirectory}/lib/acme-util-1.0.jar"}
    assert len(paths) == 2 and all(a.startswith("acme-util") for a in paths)     # distinct artifactIds
    by_path = {j.path: j for j in res.jars}
    assert by_path["web/WEB-INF/lib/acme-util-1.0.jar"].artifact_id != by_path["lib/acme-util-1.0.jar"].artifact_id

