#!/usr/bin/env python3
"""Rebuild the jars of the ant-webapp fixture (WebContent/WEB-INF/lib). Idempotent: a jar is rewritten only when its
bytes would change (fixed entry order and timestamps, so the committed files stay byte-identical).

    python3 fixtures/projects/ant-webapp/make-stubs.py           # the three stub jars
    python3 fixtures/projects/ant-webapp/make-stubs.py --util    # + example-util-1.0.jar compiled from lib-src/
                                                                  #   (javac --release 8 from $JAVA21_HOME or PATH)

Stubs (no real classes — the build never compiles against them):
  commons-lang-2.6.jar  META-INF/maven/commons-lang/commons-lang/pom.properties + org/apache/commons/lang/StringUtils.class
                        → rung ① of the jar ladder (pom.properties): commons-lang:commons-lang:2.6, the real jar comes
                        from Maven Central through the synthesized dependency
  servlet-api-2.5.jar   javax/servlet/Servlet.class → rung ② (knowledge/libraries/jar_names.yml stem servlet-api):
                        javax.servlet:servlet-api:2.5, scope provided (container API)
  old-report.jar        com/example/report/Old.class, no coordinates and no source uses com.example.report → dropped
Real jar:
  example-util-1.0.jar  com/example/util/Greeter.class compiled from lib-src/ (no pom.properties, in no table or
                        repository) — HelloServlet calls it, so the synthesis declares it with system scope and copies
                        it to <root>/lib/ (Handover: one `mvn install:install-file` line)
"""
from __future__ import annotations

import argparse
import io
import os
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
LIB = HERE / "WebContent" / "WEB-INF" / "lib"
LIB_SRC = HERE / "lib-src"
STAMP = (2010, 1, 1, 0, 0, 0)
CLASS_STUB = b"\xca\xfe\xba\xbe\x00\x00\x00\x32"          # class-file magic + version 50 (Java 6), no body
MANIFEST = "Manifest-Version: 1.0\r\nCreated-By: make-stubs.py (sbmig ant-webapp fixture)\r\n\r\n"

STUBS: dict[str, dict[str, bytes | str]] = {
    "commons-lang-2.6.jar": {
        "META-INF/MANIFEST.MF": MANIFEST,
        "META-INF/maven/commons-lang/commons-lang/pom.properties":
            "#Generated by Maven\ngroupId=commons-lang\nartifactId=commons-lang\nversion=2.6\n",
        "org/apache/commons/lang/StringUtils.class": CLASS_STUB,
    },
    "servlet-api-2.5.jar": {
        "META-INF/MANIFEST.MF": MANIFEST,
        "javax/servlet/Servlet.class": CLASS_STUB,
    },
    "old-report.jar": {
        "META-INF/MANIFEST.MF": MANIFEST,
        "com/example/report/Old.class": CLASS_STUB,
    },
}


def zip_bytes(entries: dict[str, bytes | str]) -> bytes:
    """A jar with the entries in the given order, every entry dated STAMP (deterministic bytes)."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        dirs: list[str] = []
        for name in entries:
            parts = name.split("/")[:-1]
            for i in range(1, len(parts) + 1):
                d = "/".join(parts[:i]) + "/"
                if d not in dirs:
                    dirs.append(d)
        for name in dirs + list(entries):
            info = zipfile.ZipInfo(name, date_time=STAMP)
            info.external_attr = (0o40755 << 16) if name.endswith("/") else (0o644 << 16)
            info.compress_type = zipfile.ZIP_STORED if name.endswith("/") else zipfile.ZIP_DEFLATED
            data = entries.get(name, b"")
            zf.writestr(info, data.encode("utf-8") if isinstance(data, str) else data)
    return buf.getvalue()


def write_if_changed(path: Path, data: bytes) -> bool:
    if path.is_file() and path.read_bytes() == data:
        print(f"unchanged {path.relative_to(HERE)}")
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    print(f"wrote     {path.relative_to(HERE)} ({len(data)} bytes)")
    return True


def javac() -> str:
    for home in (os.environ.get("JAVA21_HOME"), os.environ.get("JAVA_HOME")):
        if home and (Path(home) / "bin" / "javac").exists():
            return str(Path(home) / "bin" / "javac")
    found = shutil.which("javac")
    if not found:
        sys.exit("javac not found: set JAVA21_HOME (or JAVA_HOME) or put javac on PATH")
    return found


def util_jar() -> bytes:
    """example-util-1.0.jar: lib-src/ compiled with `javac --release 8` (class files carry no timestamp)."""
    sources = sorted(LIB_SRC.rglob("*.java"))
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [javac(), "--release", "8", "-Xlint:-options", "-encoding", "UTF-8", "-d", tmp, *map(str, sources)]
        subprocess.run(cmd, check=True)
        classes = sorted(p for p in Path(tmp).rglob("*.class"))
        entries: dict[str, bytes | str] = {"META-INF/MANIFEST.MF": MANIFEST}
        for c in classes:
            entries[c.relative_to(tmp).as_posix()] = c.read_bytes()
    return zip_bytes(entries)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--util", action="store_true", help="also rebuild example-util-1.0.jar from lib-src/ (needs javac)")
    args = ap.parse_args(argv)
    for name, entries in STUBS.items():
        write_if_changed(LIB / name, zip_bytes(entries))
    if args.util or not (LIB / "example-util-1.0.jar").exists():
        write_if_changed(LIB / "example-util-1.0.jar", util_jar())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
