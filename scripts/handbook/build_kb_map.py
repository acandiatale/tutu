"""docs/kb-map/kb-map.html (the page source, also published as an artifact that renders Mermaid natively) →
docs/kb-map/index.html, a standalone page for the air-gapped company PC: it loads the vendored
docs/kb-map/mermaid.min.js next to it instead of a CDN, so `git pull` + double-click shows the diagrams offline.

    .venv/bin/python scripts/handbook/build_kb_map.py [path/to/mermaid.min.js]

The optional argument refreshes the vendored Mermaid (e.g. node_modules/mermaid/dist/mermaid.min.js, 11.x)."""
from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs" / "kb-map" / "kb-map.html"
OUT = ROOT / "docs" / "kb-map" / "index.html"
VENDOR = ROOT / "docs" / "kb-map" / "mermaid.min.js"

HEAD = """<!doctype html>
<html lang="ko">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<!-- generated by scripts/handbook/build_kb_map.py from kb-map.html — edit that file, then run the script -->
"""
TAIL = """
<script src="mermaid.min.js"></script>
<script>
(function () {
  if (!window.mermaid) { return; }            // the vendored file is missing: the diagrams stay as text
  var dark = document.documentElement.getAttribute("data-theme") === "dark" ||
    (!document.documentElement.getAttribute("data-theme") && window.matchMedia &&
     window.matchMedia("(prefers-color-scheme: dark)").matches);
  window.mermaid.initialize({ startOnLoad: false, theme: dark ? "dark" : "default", securityLevel: "strict",
                              er: { useMaxWidth: false }, flowchart: { useMaxWidth: false } });
  window.mermaid.run({ querySelector: "pre.mermaid" });
})();
</script>
</body>
</html>
"""


def main() -> int:
    if len(sys.argv) > 1:
        shutil.copyfile(sys.argv[1], VENDOR)
    if not VENDOR.is_file():
        print(f"missing {VENDOR}: pass the path of mermaid.min.js once", file=sys.stderr)
        return 1
    body = SRC.read_text(encoding="utf-8")
    title_end = body.index("</style>") + len("</style>")
    OUT.write_text(HEAD + body[:title_end] + "\n</head>\n<body>\n" + body[title_end:] + TAIL, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} (Mermaid: {VENDOR.name}, {VENDOR.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
