"""docs/kb-map/kb-map.html (the page source, also published as an artifact whose viewer renders Mermaid natively) →
docs/kb-map/index.html, ONE self-contained file for the air-gapped company PC: Mermaid (the vendored
scripts/handbook/vendor/mermaid.min.js, 11.x) is inlined into it, so the file alone shows every diagram offline —
copy it anywhere and double-click. The vendored script is only a build input; nothing beside index.html is needed.

    .venv/bin/python scripts/handbook/build_kb_map.py [path/to/mermaid.min.js]

The optional argument refreshes the vendored Mermaid (e.g. node_modules/mermaid/dist/mermaid.min.js)."""
from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "docs" / "kb-map" / "kb-map.html"
OUT = ROOT / "docs" / "kb-map" / "index.html"
VENDOR = ROOT / "scripts" / "handbook" / "vendor" / "mermaid.min.js"

HEAD = """<!doctype html>
<html lang="ko">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<!-- generated by scripts/handbook/build_kb_map.py from kb-map.html (Mermaid inlined) — edit kb-map.html, then run
     the script; this file alone shows every diagram, no other file and no network needed -->
"""
INIT = """
<script>
(function () {
  if (!window.mermaid) { return; }
  var dark = document.documentElement.getAttribute("data-theme") === "dark" ||
    (!document.documentElement.getAttribute("data-theme") && window.matchMedia &&
     window.matchMedia("(prefers-color-scheme: dark)").matches);
  window.mermaid.initialize({ startOnLoad: false, theme: dark ? "dark" : "default", securityLevel: "strict",
                              er: { useMaxWidth: false }, flowchart: { useMaxWidth: false } });
  window.mermaid.run({ querySelector: "pre.mermaid" });
})();
</script>
</body>
</html>
"""


def inline_script(js: str) -> str:
    """`js` safe inside one <script> element: a literal `</script` would end it early."""
    if re.search(r"<script", js, flags=re.I):
        raise SystemExit("the Mermaid build contains '<script': inlining it needs a closer look")
    return "<script>\n" + re.sub(r"</(script)", r"<\\/\1", js, flags=re.I) + "\n</script>"


def main() -> int:
    if len(sys.argv) > 1:
        VENDOR.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(sys.argv[1], VENDOR)
    if not VENDOR.is_file():
        print(f"missing {VENDOR}: pass the path of mermaid.min.js once", file=sys.stderr)
        return 1
    body = SRC.read_text(encoding="utf-8")
    style_end = body.index("</style>") + len("</style>")
    js = VENDOR.read_text(encoding="utf-8")
    page = (HEAD + body[:style_end] + "\n</head>\n<body>\n" + body[style_end:] + "\n" + inline_script(js) + INIT)
    OUT.write_text(page, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size // 1024} KB, Mermaid inlined)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
