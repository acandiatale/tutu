"""Handler ``jdk-base64-shim`` (round 10): JDK-internal Base64 classes that javac 21 (--release 21) no longer exposes.

``sun.misc.BASE64Encoder`` / ``sun.misc.BASE64Decoder`` (removed in JDK 9) and
``com.sun.org.apache.xerces.internal.impl.dv.util.Base64`` (JDK-internal, not exported) are everywhere in 2013–2020
Korean enterprise code. ``UseJavaUtilBase64`` (UpgradeToJava21) cannot touch them on JDK 21 — their types no longer
resolve — so they used to cost an LLM call per file. The handler instead generates small drop-in classes
``sbmig.compat.BASE64Encoder`` / ``BASE64Decoder`` / ``Base64`` in each source root that needs them and points the
references there (imports, fully-qualified names, wildcard imports), so call sites compile unchanged:

* ``BASE64Encoder.encode`` / ``encodeBuffer`` produce exactly what JDK 8 produced (standard alphabet, '=' padding,
  76-character lines separated by ``System.lineSeparator()``; ``encode`` ends a line only when another one follows —
  and after an exactly full last line —, ``encodeBuffer`` ends every line), byte-for-byte compared with
  corretto-1.8.0_362 for 350 lengths and both separators;
* ``BASE64Decoder.decodeBuffer`` keeps ``throws IOException`` (callers' ``catch (IOException e)`` still compiles),
  skips line breaks, accepts missing padding (JDK 8 appended garbage bytes there; the shim returns the correct ones);
* ``Base64.encode`` / ``decode`` keep the Xerces contract (no line breaks; ``null`` for malformed input), compared with
  the JDK 8 class for 200 000 random inputs.

Pre-emptive before the first JDK 21 build (advisory ``jdk-removed-apis`` detected) and reactive on the javac errors;
idempotent (an existing shim file is never overwritten). Subclasses of the JDK classes (overriding
``bytesPerLine()`` & co) are not handled — the build reports them and the LLM ports them.
"""
from __future__ import annotations

import logging
import posixpath
import re
from typing import Optional

from sbmig.core.models import ErrorCluster, ErrorKind, Phase, ProjectProfile
from sbmig.core.workspace import Workspace

from .edge_handlers import EdgeHandler
