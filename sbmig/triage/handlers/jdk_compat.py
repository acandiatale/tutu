log = logging.getLogger("sbmig.triage.handlers.jdk_compat")

COMPAT_PACKAGE = "sbmig.compat"
SUN_ENCODER = "sun.misc.BASE64Encoder"
SUN_DECODER = "sun.misc.BASE64Decoder"
XERCES = "com.sun.org.apache.xerces.internal.impl.dv.util.Base64"
# old FQCN → shim simple name
SHIMS = {SUN_ENCODER: "BASE64Encoder", SUN_DECODER: "BASE64Decoder", XERCES: "Base64"}
_WILDCARD_PKGS = {"sun.misc": (SUN_ENCODER, SUN_DECODER),
                  "com.sun.org.apache.xerces.internal.impl.dv.util": (XERCES,)}
_GONE_PKGS = frozenset({"com.sun.org.apache.xerces.internal.impl.dv.util"})   # sun.misc stays (Unsafe, jdk.unsupported)
_PACKAGE_RE = re.compile(r"^[ \t]*package\s+([\w.]+)\s*;", re.M)

_HEADER = "// Generated by sbmig (handler jdk-base64-shim). Safe to keep; new code should use java.util.Base64.\n"

ENCODER_SOURCE = _HEADER + """package sbmig.compat;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.util.Base64;

/**
 * Drop-in replacement for the JDK 8 internal {@code sun.misc.BASE64Encoder} (removed in JDK 9). Same output:
 * standard alphabet with '=' padding, lines of 76 characters (57 input bytes) separated by
 * {@code System.lineSeparator()}; {@code encode} ends a line only when another one follows (and after an exactly
 * full last line), {@code encodeBuffer} ends every line.
 */
public class BASE64Encoder {

    private static final int BYTES_PER_LINE = 57;

    public String encode(byte[] data) {
        return text(data, false);
    }

    public String encode(ByteBuffer buffer) {
        return encode(remaining(buffer));
    }

    public void encode(byte[] data, OutputStream out) throws IOException {
        out.write(text(data, false).getBytes(StandardCharsets.ISO_8859_1));
    }

    public void encode(ByteBuffer buffer, OutputStream out) throws IOException {
        encode(remaining(buffer), out);
    }

    public void encode(InputStream in, OutputStream out) throws IOException {
        encode(readAll(in), out);
    }

    public String encodeBuffer(byte[] data) {
        return text(data, true);
    }

    public String encodeBuffer(ByteBuffer buffer) {
        return encodeBuffer(remaining(buffer));
    }

    public void encodeBuffer(byte[] data, OutputStream out) throws IOException {
        out.write(text(data, true).getBytes(StandardCharsets.ISO_8859_1));
    }

    public void encodeBuffer(ByteBuffer buffer, OutputStream out) throws IOException {
        encodeBuffer(remaining(buffer), out);
    }

    public void encodeBuffer(InputStream in, OutputStream out) throws IOException {
        encodeBuffer(readAll(in), out);
    }

    private static String text(byte[] data, boolean terminateEveryLine) {
        if (data.length == 0) {
            return "";
        }
        String sep = System.lineSeparator();
        String body = Base64.getMimeEncoder(76, sep.getBytes(StandardCharsets.ISO_8859_1)).encodeToString(data);
        if (terminateEveryLine || data.length % BYTES_PER_LINE == 0) {
            return body + sep;
        }
        return body;
    }

    private static byte[] remaining(ByteBuffer buffer) {
        byte[] b = new byte[buffer.remaining()];
        buffer.get(b);
        return b;
    }

    static byte[] readAll(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        byte[] chunk = new byte[8192];
        int n;
        while ((n = in.read(chunk)) != -1) {
            out.write(chunk, 0, n);
        }
        return out.toByteArray();
    }
}
"""

DECODER_SOURCE = _HEADER + """package sbmig.compat;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.util.Base64;

/**
 * Drop-in replacement for the JDK 8 internal {@code sun.misc.BASE64Decoder} (removed in JDK 9). Line breaks are
 * skipped, missing '=' padding is accepted, and the methods keep {@code throws IOException} (malformed input is
 * reported as an IOException, as before).
 */
public class BASE64Decoder {

    public byte[] decodeBuffer(String text) throws IOException {
        return decode(text.getBytes(StandardCharsets.ISO_8859_1));
    }

    public byte[] decodeBuffer(InputStream in) throws IOException {
        return decode(readAll(in));
    }

    public void decodeBuffer(InputStream in, OutputStream out) throws IOException {
        out.write(decodeBuffer(in));
    }

    public ByteBuffer decodeBufferToByteBuffer(String text) throws IOException {
        return ByteBuffer.wrap(decodeBuffer(text));
    }

    public ByteBuffer decodeBufferToByteBuffer(InputStream in) throws IOException {
        return ByteBuffer.wrap(decodeBuffer(in));
    }

    private static byte[] decode(byte[] data) throws IOException {
        try {
            return Base64.getMimeDecoder().decode(data);
        } catch (IllegalArgumentException e) {
            throw new IOException(e.getMessage(), e);
        }
    }

    private static byte[] readAll(InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        byte[] chunk = new byte[8192];
        int n;
        while ((n = in.read(chunk)) != -1) {
            out.write(chunk, 0, n);
        }
        return out.toByteArray();
    }
}
"""

XERCES_SOURCE = _HEADER + """package sbmig.compat;

/**
 * Drop-in replacement for the JDK-internal {@code com.sun.org.apache.xerces.internal.impl.dv.util.Base64} (not
 * accessible with --release 21). Same contract: {@code encode} without line breaks ({@code null} for {@code null}),
 * {@code decode} skips blanks / tabs / line breaks and returns {@code null} for malformed input (length not a
 * multiple of 4, characters outside the alphabet, padding in the wrong place, non-zero padding bits).
 */
public final class Base64 {

    private Base64() {
    }

    public static String encode(byte[] binaryData) {
        if (binaryData == null) {
            return null;
        }
        return java.util.Base64.getEncoder().encodeToString(binaryData);
    }

    public static byte[] decode(String encoded) {
        if (encoded == null) {
            return null;
        }
        StringBuilder sb = new StringBuilder(encoded.length());
        for (int i = 0; i < encoded.length(); i++) {
            char c = encoded.charAt(i);
            if (c != ' ' && c != '\\t' && c != '\\r' && c != '\\n') {
                sb.append(c);
            }
        }
        int len = sb.length();
        if (len % 4 != 0) {
            return null;
        }
        if (len == 0) {
            return new byte[0];
        }
        String s = sb.toString();
        int pad = s.endsWith("==") ? 2 : (s.endsWith("=") ? 1 : 0);
        for (int i = 0; i < len - pad; i++) {
            if (value(s.charAt(i)) < 0) {
                return null;
            }
        }
        if (pad == 2 && (value(s.charAt(len - 3)) & 0xf) != 0) {
            return null;
        }
        if (pad == 1 && (value(s.charAt(len - 2)) & 0x3) != 0) {
            return null;
        }
        return java.util.Base64.getDecoder().decode(s);
    }

    private static int value(char c) {
        if (c >= 'A' && c <= 'Z') {
            return c - 'A';
        }
        if (c >= 'a' && c <= 'z') {
            return c - 'a' + 26;
        }
        if (c >= '0' && c <= '9') {
            return c - '0' + 52;
        }
        if (c == '+') {
            return 62;
        }
        if (c == '/') {
            return 63;
        }
        return -1;
    }
}
"""

SHIM_SOURCES = {"BASE64Encoder": ENCODER_SOURCE, "BASE64Decoder": DECODER_SOURCE, "Base64": XERCES_SOURCE}


def _fq_regex() -> re.Pattern:
    return re.compile(r"(?<![\w$.])(" + "|".join(re.escape(k) for k in sorted(SHIMS, key=len, reverse=True))
                      + r")(?![\w$])")


def point_to_shims(text: str) -> tuple[str, set[str]]:
    """(new text, shim simple names the file now needs). Fully-qualified references (imports included) outside
    literals / comments move to sbmig.compat.*; a wildcard import of sun.misc (still a JDK package) gets explicit
    shim imports for the simple names the file uses; the xerces wildcard (inaccessible package) is replaced."""
    needed: set[str] = set()
    spans = [(m.start(), m.end()) for m in _LIT_RE.finditer(text)]
    out, last = [], 0
    for m in _fq_regex().finditer(text):
        if _in_spans(m.start(), spans):
            continue
        out.append(text[last:m.start()])
        simple = SHIMS[m.group(1)]
        out.append(f"{COMPAT_PACKAGE}.{simple}")
        needed.add(simple)
        last = m.end()
    out.append(text[last:])
    text = "".join(out)
    wild = {name for _a, _b, static, name, star in imports_of(text) if star and not static}
    hits = [p for p in _WILDCARD_PKGS if p in wild]
    if hits:
        body = _body_mask(text)
        taken = {name.rsplit(".", 1)[-1] for _a, _b, static, name, star in imports_of(text)
                 if not static and not star and not name.startswith(COMPAT_PACKAGE + ".")}
        # a single-type import of the same simple name (java.util.Base64) already decides what the name means
        add = [old for p in hits for old in _WILDCARD_PKGS[p]
               if _uses_simple(body, SHIMS[old]) and SHIMS[old] not in taken]
        gone = {p for p in hits if p in _GONE_PKGS}
        if gone:
            text = remove_import_lines(text, lambda static, name, star: star and not static and name in gone)
        if add:
            # an explicit single-type import beats the java.util.Base64 / sun.misc.* wildcard on the simple name
            text = add_imports(text, [f"{COMPAT_PACKAGE}.{SHIMS[o]}" for o in add])
            needed |= {SHIMS[o] for o in add}
    return text, needed


def source_root(rel: str, text: str) -> Optional[str]:
    """Source root of a Java file: its path minus the package directories (None when they do not match)."""
    norm = rel.replace("\\", "/")
    d = posixpath.dirname(norm)
    m = _PACKAGE_RE.search(text)
    pkg_path = m.group(1).replace(".", "/") if m else ""
    if not pkg_path:
        return d
    if d == pkg_path:
        return ""
    if d.endswith("/" + pkg_path):
        return d[: -len(pkg_path) - 1]
    return None


def _module_key(root: str) -> tuple[str, bool]:
    """(module dir, is test root) for a source root (`<m>/src/test/java` → (`<m>`, True))."""
    r = "/" + root.strip("/")
    for marker, test in (("/src/test/", True), ("/src/main/", False)):
        i = r.find(marker)
        if i >= 0:
            return r[:i].lstrip("/"), test
    return root, False


class JdkBase64Shim(EdgeHandler):
    id = "jdk-base64-shim"
    description = ("sun.misc.BASE64Encoder/Decoder and the JDK-internal xerces Base64 → generated drop-in classes "
                   "sbmig.compat.* (JDK 8 output, call sites unchanged)")
    kinds = frozenset({ErrorKind.COMPILE, ErrorKind.TEST_COMPILE})
    triggers = (r"BASE64(?:En|De)coder", r"com\.sun\.org\.apache\.xerces\.internal\.impl\.dv\.util",
                r"symbol:\s+class (?:BASE64Encoder|BASE64Decoder)\b")
    preemptive_phase = Phase.JDK21

    def applicable(self, cluster: Optional[ErrorCluster], profile: Optional[ProjectProfile], cfg) -> bool:
        if cluster is not None or profile is None:
            return True
        return profile.has_library("jdk-removed-apis")

    def edit(self, ws: Workspace, cluster, profile, cfg) -> list[str]:
        files = [f for f in ws.java_files() if not _under_target(f)]
        changed: list[str] = []
        need_by_root: dict[str, set[str]] = {}
        unplaced: list[str] = []
        pending: dict[str, str] = {}
        shim_tails = tuple(f"sbmig/compat/{n}.java" for n in SHIM_SOURCES)
        for f in files:
            if f.replace("\\", "/").endswith(shim_tails):
                continue
            try:
                text = ws.read(f)
            except OSError:
                continue
            if "BASE64" not in text and "xerces" not in text:
                continue
            new, needed = point_to_shims(text)
            if not needed or new == text:
                continue
            root = source_root(f, text)
            if root is None:
                unplaced.append(f)
                continue
            pending[f] = new
            need_by_root.setdefault(root, set()).update(needed)
        if not pending:
            if unplaced:
                self.note(f"follow-up: sun.misc / xerces Base64 in {', '.join(unplaced[:3])} not shimmed (package "
                          "declaration does not match the directory) — port to java.util.Base64")
            return []
        # one shim set per module: a test root whose module also has a main root that needs shims uses those
        roots = self._placement(need_by_root)
        created: list[str] = []
        for root, names in sorted(roots.items()):
            for name in sorted(names):
                rel = posixpath.join(root, "sbmig", "compat", f"{name}.java") if root else f"sbmig/compat/{name}.java"
                if ws.exists(rel):
                    continue
                ws.write(rel, SHIM_SOURCES[name])
                created.append(rel)
        for f, new in pending.items():
            ws.write(f, new)
            changed.append(f)
        self.flag("jdk-base64-shimmed")
        self.note(f"sun.misc.BASE64Encoder/Decoder / xerces Base64 → generated sbmig.compat shims ({', '.join(created) or 'existing'}) "
                  f"for {len(changed)} file(s) (e.g. {', '.join(changed[:3])}): JDK 8 behaviour kept (76-character "
                  "lines, decodeBuffer throws IOException); follow-up: move to java.util.Base64 when convenient")
        if unplaced:
            self.note(f"follow-up: sun.misc / xerces Base64 in {', '.join(unplaced[:3])} not shimmed (package "
                      "declaration does not match the directory) — port to java.util.Base64")
        log.info("jdk-base64-shim: %d file(s), shims %s", len(changed), created)
        return changed + created

    @staticmethod
    def _placement(need_by_root: dict[str, set[str]]) -> dict[str, set[str]]:
        by_module: dict[str, dict[bool, list[str]]] = {}
        for root in need_by_root:
            mod, test = _module_key(root)
            by_module.setdefault(mod, {}).setdefault(test, []).append(root)
        out: dict[str, set[str]] = {}
        for mod, kinds in by_module.items():
            mains = kinds.get(False, [])
            tests = kinds.get(True, [])
            if mains:
                target = sorted(mains)[0]
                out[target] = set().union(*(need_by_root[r] for r in mains + tests))
                for r in sorted(mains)[1:]:              # several main roots in one module dir: each its own copy
                    out[r] = set(need_by_root[r])
            else:
                for r in tests:
                    out[r] = set(need_by_root[r])
        return out


def jdk_compat_handlers(cfg=None) -> list:
    return [JdkBase64Shim()]


