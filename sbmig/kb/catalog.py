        lines.append(f"| `{r['id']}` | {_md(r['name'])} | {_md(r['status'])} | {_md(r['action'])} | {r['seen']} | "
                     f"{r['projects']} | {_md(r['resolved_by'])} | {_md(r['latest_fix'])} | "
                     f"{_md(r['top_failure'])} |")
